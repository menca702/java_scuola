public class Dischetto {
  
    private int numero;
    private String immagine;
    
    public Dischetto(int numero, String immagine) {
        this.numero = numero;
        this.immagine = immagine;
    }

    public int getNumero() {
        return numero;
    }

    public String getImmagine() {
        return immagine;
    }

    
}